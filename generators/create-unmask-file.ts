import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import sharp from 'sharp'
import { ISOCountryCodes } from '../data/iso-codes.gen'
import { unmaskFacts, unmaskPortraitKey } from '../lib/unmask'
import { UNMASK_SOURCE_SIZE } from '../lib/unmask-pace'
import { jsonParseLiteral } from './lib/emit'

/**
 * Unmask's server-only file data, derived from what the leaders and parties
 * generators already saved: each subject's portrait as a 32×32 RGB source the
 * dealer cuts every tier from, and the governing party's logo under a name
 * that is not its country. The roster's own files are `XX-Q….webp`, so a logo
 * shown under its own path would answer the round.
 *
 * Re-run after `generate:leaders` or `generate:parties`; a subject whose
 * portrait is missing here is simply never dealt.
 *
 *   bun run generate:unmask
 */

const OUTPUT_FILE = 'data/unmask.gen.ts'
const LOGO_DIRECTORY = 'public/unmask'
const LOGO_WIDTH = 240

const opaqueName = (bytes: Buffer) => createHash('sha256').update(bytes).digest('hex').slice(0, 20)

const portraits: Record<string, string> = {}
const logos: Record<string, string> = {}

rmSync(LOGO_DIRECTORY, { recursive: true, force: true })
mkdirSync(LOGO_DIRECTORY, { recursive: true })

for (const isoCode of ISOCountryCodes) {
  const facts = unmaskFacts(isoCode)
  if (!facts?.leader.image) continue
  const source = readFileSync(`public${facts.leader.image}`)
  const raw = await sharp(source)
    .resize(UNMASK_SOURCE_SIZE, UNMASK_SOURCE_SIZE, {
      fit: 'cover',
      position: sharp.strategy.attention,
    })
    .removeAlpha()
    .raw()
    .toBuffer()
  portraits[unmaskPortraitKey(facts.leader)] = raw.toString('base64')

  if (facts.logo && !logos[facts.logo.path]) {
    const bytes = await sharp(readFileSync(`public${facts.logo.path}`))
      .resize({ width: LOGO_WIDTH, height: LOGO_WIDTH, fit: 'inside', withoutEnlargement: true })
      .webp()
      .toBuffer()
    const published = `/unmask/${opaqueName(bytes)}.webp`
    writeFileSync(`public${published}`, bytes)
    logos[facts.logo.path] = published
  }
}

writeFileSync(
  OUTPUT_FILE,
  `// Generated by generators/create-unmask-file.ts — do not edit by hand.
// Derived from the portraits in public/leaders and the logos in public/parties.
// The answers' raw material: server-only, never imported outside lib/events/server.

/** Portrait sources, ${UNMASK_SOURCE_SIZE}×${UNMASK_SOURCE_SIZE} RGB in base64, by \`unmaskPortraitKey\`. */
export const UNMASK_PORTRAITS: Record<string, string> = ${jsonParseLiteral(portraits)}

/** Roster logo path → its opaque published copy. */
export const UNMASK_LOGOS: Record<string, string> = ${jsonParseLiteral(logos)}
`
)

console.log(
  `Wrote ${Object.keys(portraits).length} portraits and ${Object.keys(logos).length} logos to ${OUTPUT_FILE}`
)
