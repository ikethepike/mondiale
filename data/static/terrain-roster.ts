import type { Fame } from '~~/types/fame.types'
import type { ISOCountryCode } from '~~/types/geography.types'

/**
 * Every subject Lay of the Land deals, with its answer key written by hand.
 * The generator derives shores and hosts from Natural Earth geometry, and that
 * derivation misses a river that IS a border (Moldova's 500m of Danube) and
 * invents shores a coarse polygon brushes past — so it only draws these
 * subjects. `create-water.ts` stamps this table onto `WATER_FEATURES` and
 * writes `generators/data/terrain-report.txt`, the geometry's disagreements
 * for a human to rule on after an NE bump.
 *
 * Keyed by the WATER_FEATURES id NE's name produces. Rivers list their
 * countries source to mouth. Re-run `bun run generate:water` after editing.
 */
export interface TerrainEntry {
  fame: Fame
  /** Every country a full sweep names. */
  required: ISOCountryCode[]
  /** True of the world but arguable — a basin, a boundary shore, a marginal
   *  sea's coast. Naming one is free; it is never required. */
  accepted?: ISOCountryCode[]
  /** The headline when NE's name is not the one players know; NE's becomes an alias. */
  name?: string
  aliases?: string[]
  /** Reads without "the": Lake Victoria, Central America. */
  bare?: true
}

